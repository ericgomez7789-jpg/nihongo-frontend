/* ==========================================================
   PLAYER BOARD
========================================================== */

function renderPlayerBoard(
    player
) {

    const container =
        document.getElementById(

            player === 1
                ? "kaiwaContainer1"
                : "kaiwaContainer2"

        );

    container.innerHTML = "";

    const choices =
        shuffleArray(
            [...kaiwaCurrentSentence.choices]
        );

    choices.forEach(choice => {

        const btn =
            document.createElement(
                "button"
            );

        btn.className =
            "kaiwaBtn";

        btn.textContent =
            choice;

        btn.addEventListener(
            "click",
            () => {

                checkKaiwaAnswer(
                    player,
                    choice,
                    btn
                );

            }
        );

        container.appendChild(
            btn
        );

    });

}


/* ==========================================================
   CHECK ANSWER
========================================================== */

function checkKaiwaAnswer(
    player,
    selectedChoice,
    button
) {

    if (
        selectedChoice ===
        kaiwaCurrentSentence.answer
    ) {

        button.classList.add(
            "correct"
        );

        kaiwaPlayerWins(
            player
        );

    }
    else {

        button.classList.add(
            "wrong"
        );

        button.disabled = true;

        if (player === 1) {
            kaiwaPlayer1Out = true;
        } else {
            kaiwaPlayer2Out = true;
        }

        // Disable all buttons for that player
        const container =
            document.getElementById(
                player === 1
                    ? "kaiwaContainer1"
                    : "kaiwaContainer2"
            );

        container
            .querySelectorAll("button")
            .forEach(btn => {
                btn.disabled = true;
            });

        // If both players are out, nobody wins
        if (
            kaiwaPlayer1Out &&
            kaiwaPlayer2Out
        ) {

            clearInterval(
                kaiwaTimerInterval
            );

            setTimeout(() => {
                kaiwaNextRound();
            }, 2000);

        }

    }

}


/* ==========================================================
   PLAYER WIN
========================================================== */

function kaiwaPlayerWins(
    player
) {

    clearInterval(
        kaiwaTimerInterval
    );

    if (player === 1) {

        kaiwaScore1++;

    }
    else {

        kaiwaScore2++;

    }

    updateKaiwaScorekeepers();

    KaiwaProgress.markSentenceComplete(
        "kaiwa",
        kaiwaCurrentSentence.id
    );

    KAIWA.renderProgress();

    const reveal =
        document.getElementById(
            "kaiwaReveal"
        );

    reveal.innerHTML = `
        <div>
            ${kaiwaCurrentSentence.answer}
        </div>
    `;

    reveal.style.display =
        "block";

    setTimeout(() => {

        reveal.style.display =
            "none";

        kaiwaNextRound();

    }, 5000);

}


