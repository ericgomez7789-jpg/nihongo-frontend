/* ==========================================================
   TIMER
========================================================== */

function startKaiwaTimer(
    onExpire
) {

    let timeLeft = 60;

    const timer =
        document.getElementById(
            "kaiwaTimer"
        );

    timer.textContent =
        timeLeft;

    clearInterval(
        kaiwaTimerInterval
    );

    kaiwaTimerInterval =
        setInterval(() => {

            timeLeft--;

            timer.textContent =
                timeLeft;

            if (timeLeft <= 0) {

                clearInterval(
                    kaiwaTimerInterval
                );

                onExpire();

            }

        }, 1000);

}


