/* ==========================================================
   AUDIO
========================================================== */

function stopAllKaiwaAudio() {

    if (currentKaiwaAudio) {

        try {

            currentKaiwaAudio.pause();

            currentKaiwaAudio.currentTime = 0;

        } catch (e) {}

    }

}


/* ==========================================================
   SCREEN
========================================================== */

function kaiwa() {

    stopAllKaiwaAudio();

    window.currentLevel = "kaiwa";

    kaiwaScore1 = 0;
    kaiwaScore2 = 0;

    kaiwaRound = 0;

    updateKaiwaScorekeepers();

    KaiwaProgress.setTotal(
        "kaiwa",
        kaiwaSentences.length
    );

    KAIWA.renderProgress();

    wireKaiwaReplayButton();

    showScreen(
        "kaiwaScreen"
    );

    kaiwaNextRound();

}




function showScreen(id) {

    document
        .querySelectorAll(".screen")
        .forEach(screen => {

            screen.classList.add(
                "hidden"
            );

        });

    const screen =
        document.getElementById(
            id
        );

    if (screen) {

        screen.classList.remove(
            "hidden"
        );

    }

}


/* ==========================================================
   PROGRESS
========================================================== */

window.KAIWA =
    window.KAIWA || {};

KAIWA.renderProgress =
function () {

    const currentRound =
        Math.min(
            Math.max(
                kaiwaRound,
                1
            ),
            5
        );

    const totalRounds = 5;

    const percent =
        (currentRound /
         totalRounds) * 100;

    const wrappers =
        document.querySelectorAll(
            "#kaiwaProgress1, #kaiwaProgress2"
        );

    wrappers.forEach(wrapper => {

        const label =
            wrapper.querySelector(
                ".kaiwa-progress-label"
            );

        const bar =
            wrapper.querySelector(
                ".kaiwa-progress-bar"
            );

        if (label) {

            label.textContent =
                `Round: ${currentRound} / ${totalRounds}`;

        }

        if (bar) {

            bar.style.width =
                `${percent}%`;

        }

    });

};


