function checkKnockout() {

    const status =
        document.getElementById(
            "boxingStatus"
        );

    if (
        Boxing.boxer1HP <= 0
    ) {

        document
            .getElementById(
                "boxer1Sprite"
            )
            .classList.add(
                "knockout"
            );

        status.textContent =
            "🥊 KNOCKOUT! PLAYER 2 WINS!";

        setTimeout(
            boxing,
            5000
        );

        return;

    }

    if (
        Boxing.boxer2HP <= 0
    ) {

        document
            .getElementById(
                "boxer2Sprite"
            )
            .classList.add(
                "knockout"
            );

        status.textContent =
            "🥊 KNOCKOUT! PLAYER 1 WINS!";

        setTimeout(
            boxing,
            5000
        );

        return;

    }

    setTimeout(() => {

        boxingNextRound();

    }, 1500);

}

