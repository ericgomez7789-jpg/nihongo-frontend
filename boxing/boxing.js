function startBoxingTimer() {

    let timeLeft = 30;

    const timer =
        document.getElementById(
            "boxingTimer"
        );

    timer.textContent =
        timeLeft;

    clearInterval(
        Boxing.timer
    );

    Boxing.timer =
        setInterval(() => {

            timeLeft--;

            timer.textContent =
                timeLeft;

            if (
                timeLeft <= 0
            ) {

                clearInterval(
                    Boxing.timer
                );

                boxingNextRound();

            }

        }, 1000);

}

