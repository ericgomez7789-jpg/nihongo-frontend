/* ==========================================================
   GLOBAL VARIABLES
========================================================== */

let miwakeruScore1 = 0;
let miwakeruScore2 = 0;

let miwakeruRound = 0;

let miwakeruCurrentSentence = null;

let miwakeruTimerInterval = null;

let currentSentenceAudio = null;




/* ==========================================================
   AUDIO
========================================================== */

function stopAllAudio() {

    if (currentSentenceAudio) {

        try {

            currentSentenceAudio.pause();
            currentSentenceAudio.currentTime = 0;

        } catch (e) {}

    }

}



function showScreen(id) {

  document
    .querySelectorAll(".screen")
    .forEach(screen => {
      screen.classList.add("hidden");
    });

  const screen =
    document.getElementById(id);

  if (screen) {
    screen.classList.remove("hidden");
  }

}

/* ==========================================================
   SCREEN
========================================================== */

function miwakeru() {

    stopAllAudio();

    window.currentLevel = "miwakeru";

    miwakeruScore1 = 0;
    miwakeruScore2 = 0;

    miwakeruRound = 0;

    updateMiwakeruScorekeepers();

    MiwakeruProgress.setTotal(
        "miwakeru",
        miwakeruSentences.length
    );

    MIWAKERU.renderProgress();

    wireMiwakeruReplayButton();

    showScreen("miwakeruScreen");

    miwakeruNextRound();
}

/* ==========================================================
   PROGRESS
========================================================== */

window.MIWAKERU = window.MIWAKERU || {};

MIWAKERU.renderProgress = function () {

    const currentRound =
        Math.min(
            Math.max(miwakeruRound, 1),
            5
        );

    const totalRounds = 5;

    const percent =
        (currentRound / totalRounds) * 100;

    const wrappers =
        document.querySelectorAll(
            "#miwakeruProgress1, #miwakeruProgress2"
        );

    wrappers.forEach(wrapper => {

        const label =
            wrapper.querySelector(
                ".miwakeru-progress-label"
            );

        const bar =
            wrapper.querySelector(
                ".miwakeru-progress-bar"
            );

        if (label) {

            label.textContent =
                `Round: ${currentRound} / ${totalRounds}`;

        }

        if (bar) {

            bar.style.width =
                `${percent}%`;

        }

    });

};

/* ==========================================================
   PLAYER BOARD
========================================================== */

function renderMiwakeruBoard(player) {

    const container =
        document.getElementById(
            player === 1
                ? "miwakeruChoices1"
                : "miwakeruChoices2"
        );

    container.innerHTML = "";

    const choices =
        shuffleArray(
            [...miwakeruCurrentSentence.choices]
        );

    choices.forEach(choice => {

        const btn =
            document.createElement(
                "button"
            );

        btn.className =
            "miwakeruBtn";

        btn.textContent =
            choice;

        btn.addEventListener(
            "click",
            () => {

                checkMiwakeruAnswer(
                    player,
                    choice,
                    btn
                );

            }
        );

        container.appendChild(btn);

    });

}

/* ==========================================================
   CHECK ANSWER
========================================================== */

function checkMiwakeruAnswer(
    player,
    selectedChoice,
    button
) {

    if (
        selectedChoice ===
        miwakeruCurrentSentence.answer
    ) {

        button.classList.add(
            "correct"
        );

        miwakeruPlayerWins(player);

    } else {

        button.classList.add(
            "wrong"
        );

    }

}

/* ==========================================================
   PLAYER WIN
========================================================== */

function miwakeruPlayerWins(player) {

    clearInterval(
        miwakeruTimerInterval
    );

    if (player === 1) {

        miwakeruScore1++;

    } else {

        miwakeruScore2++;

    }

    updateMiwakeruScorekeepers();

    MiwakeruProgress.markSentenceComplete(
        "miwakeru",
        miwakeruCurrentSentence.id
    );

    MIWAKERU.renderProgress();

    const reveal =
        document.getElementById(
            "miwakeruReveal"
        );

    reveal.innerHTML = `
        <div class="miwakeru-english">
            ${miwakeruCurrentSentence.answer}
        </div>
    `;

    reveal.style.display =
        "block";

    setTimeout(() => {

        reveal.style.display =
            "none";

        miwakeruNextRound();

    }, 5000);

}

/* ==========================================================
   SCOREKEEPERS
========================================================== */

function updateMiwakeruScorekeepers() {

    document.getElementById(
        "miwakeruScore1"
    ).textContent =
        miwakeruScore1;

    document.getElementById(
        "miwakeruScore2"
    ).textContent =
        miwakeruScore2;

}

/* ==========================================================
   TIMER
========================================================== */

function startMiwakeruTimer(
    onExpire
) {

    let timeLeft = 30;

    const timer =
        document.getElementById(
            "miwakeruTimer"
        );

    timer.textContent =
        timeLeft;

    clearInterval(
        miwakeruTimerInterval
    );

    miwakeruTimerInterval =
        setInterval(() => {

            timeLeft--;

            timer.textContent =
                timeLeft;

            if (timeLeft <= 0) {

                clearInterval(
                    miwakeruTimerInterval
                );

                onExpire();

            }

        }, 1000);

}

/* ==========================================================
   REPLAY BUTTON
========================================================== */

function wireMiwakeruReplayButton() {

    const btn =
        document.getElementById(
            "miwakeruReplayBtn"
        );

    if (!btn) return;

    btn.onclick = () => {

        playMiwakeruSentence(
            miwakeruCurrentSentence
        );

    };

}

/* ==========================================================
   AUDIO
========================================================== */

function playMiwakeruSentence(
    sentence
) {

    stopAllAudio();

    currentSentenceAudio =
        new Audio(
            sentence.audio
        );

    currentSentenceAudio.play();

}

/* ==========================================================
   SHUFFLE
========================================================== */

function shuffleArray(arr) {

    const copy = [...arr];

    for (
        let i = copy.length - 1;
        i > 0;
        i--
    ) {

        const j =
            Math.floor(
                Math.random() *
                (i + 1)
            );

        [copy[i], copy[j]] =
        [copy[j], copy[i]];

    }

    return copy;

}

/* ==========================================================
   NEXT ROUND
========================================================== */

function miwakeruNextRound() {

    miwakeruRound++;

    MIWAKERU.renderProgress();

    if (miwakeruRound > 5) {

        clearInterval(
            miwakeruTimerInterval
        );

        alert(`Game Over!

Player 1: ${miwakeruScore1}
Player 2: ${miwakeruScore2}`);

        miwakeru();

        return;

    }

    miwakeruCurrentSentence =
        miwakeruSentences[
            Math.floor(
                Math.random() *
                miwakeruSentences.length
            )
        ];

    renderMiwakeruBoard(1);
    renderMiwakeruBoard(2);

    playMiwakeruSentence(
        miwakeruCurrentSentence
    );

    startMiwakeruTimer(
        miwakeruNextRound
    );

}

