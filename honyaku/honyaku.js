/* ==========================================================
   GLOBAL VARIABLES
========================================================== */

let honyakuScore1 = 0;
let honyakuScore2 = 0;

let honyakuRound = 0;

let honyakuCurrentSentence = null;

let honyakuTimerInterval = null;

let currentSentenceAudio = null;





function showScreen(id) {

  document
    .querySelectorAll(".screen")
    .forEach(screen => {
      screen.classList.add("hidden");
    });

  const screen =
    document.getElementById(id);

  if (screen) {
    screen.classList.remove("hidden");
  }

}

/* ==========================================================
   AUDIO
========================================================== */

function stopAllAudio() {

    if (currentSentenceAudio) {

        try {

            currentSentenceAudio.pause();
            currentSentenceAudio.currentTime = 0;

        } catch (e) {}

    }

}


/* ==========================================================
   SCREEN
========================================================== */

function honyaku() {

    stopAllAudio();

    window.currentLevel = "honyaku";

    honyakuScore1 = 0;
    honyakuScore2 = 0;

    honyakuRound = 0;

    updateHonyakuScorekeepers();

    HonyakuProgress.setTotal(
        "honyaku",
        honyakuSentences.length
    );

    HONYAKU.renderProgress();

    wireHonyakuReplayButton();

    showScreen("honyakuScreen");

    honyakuNextRound();
}


/* ==========================================================
   PROGRESS
========================================================== */

window.HONYAKU = window.HONYAKU || {};

HONYAKU.renderProgress = function () {

    const currentRound =
        Math.min(
            Math.max(honyakuRound, 1),
            5
        );

    const totalRounds = 5;

    const percent =
        (currentRound / totalRounds) * 100;

    const wrappers =
        document.querySelectorAll(
            "#honyakuProgress1, #honyakuProgress2"
        );

    wrappers.forEach(wrapper => {

        const label =
            wrapper.querySelector(
                ".honyaku-progress-label"
            );

        const bar =
            wrapper.querySelector(
                ".honyaku-progress-bar"
            );

        if (label) {

            label.textContent =
                `Round: ${currentRound} / ${totalRounds}`;

        }

        if (bar) {

            bar.style.width =
                `${percent}%`;

        }

    });

};


/* ==========================================================
   PLAYER BOARD
========================================================== */

function renderPlayerBoard(player) {

    const container =
        document.getElementById(
            player === 1
                ? "translationContainer1"
                : "translationContainer2"
        );

    container.innerHTML = "";

    const choices =
        shuffleArray(
            [...honyakuCurrentSentence.choices]
        );

    choices.forEach(choice => {

        const btn =
            document.createElement("button");

        btn.className =
            "translationBtn";

        btn.textContent =
            choice;

        btn.addEventListener(
            "click",
            () => {

                checkAnswer(
                    player,
                    choice,
                    btn
                );

            }
        );

        container.appendChild(btn);

    });

}


/* ==========================================================
   CHECK ANSWER
========================================================== */

function checkAnswer(
    player,
    selectedChoice,
    button
) {

    if (
        selectedChoice ===
        honyakuCurrentSentence.answer
    ) {

        button.classList.add(
            "correct"
        );

        playerWins(player);

    } else {

        button.classList.add(
            "wrong"
        );

    }

}


/* ==========================================================
   PLAYER WIN
========================================================== */

function playerWins(player) {

    clearInterval(
        honyakuTimerInterval
    );

    if (player === 1) {

        honyakuScore1++;

    } else {

        honyakuScore2++;

    }

    updateHonyakuScorekeepers();

    HonyakuProgress.markSentenceComplete(
        "honyaku",
        honyakuCurrentSentence.id
    );

    HONYAKU.renderProgress();

    const reveal =
        document.getElementById(
            "honyakuReveal"
        );

    reveal.innerHTML = `

        <div class="honyaku-english">
            ${honyakuCurrentSentence.answer}
        </div>

    `;

    reveal.style.display =
        "block";

    setTimeout(() => {

        reveal.style.display =
            "none";

        honyakuNextRound();

    }, 5000);

}


/* ==========================================================
   SCOREKEEPERS
========================================================== */

function updateHonyakuScorekeepers() {

    document.getElementById(
        "honyakuScore1"
    ).textContent =
        honyakuScore1;

    document.getElementById(
        "honyakuScore2"
    ).textContent =
        honyakuScore2;

}


/* ==========================================================
   TIMER
========================================================== */

function startHonyakuTimer(
    onExpire
) {

    let timeLeft = 30;

    const timer =
        document.getElementById(
            "honyakuTimer"
        );

    timer.textContent =
        timeLeft;

    clearInterval(
        honyakuTimerInterval
    );

    honyakuTimerInterval =
        setInterval(() => {

            timeLeft--;

            timer.textContent =
                timeLeft;

            if (timeLeft <= 0) {

                clearInterval(
                    honyakuTimerInterval
                );

                onExpire();

            }

        }, 1000);

}


/* ==========================================================
   REPLAY BUTTON
========================================================== */

function wireHonyakuReplayButton() {

    const btn =
        document.getElementById(
            "honyakuReplayBtn"
        );

    if (!btn) return;

    btn.onclick = () => {

        playHonyakuSentence(
            honyakuCurrentSentence
        );

    };

}


/* ==========================================================
   AUDIO
========================================================== */

function playHonyakuSentence(
    sentence
) {

    stopAllAudio();

    currentSentenceAudio =
        new Audio(
            sentence.audio
        );

    currentSentenceAudio.play();

}


/* ==========================================================
   SHUFFLE
========================================================== */

function shuffleArray(arr) {

    const copy = [...arr];

    for (
        let i = copy.length - 1;
        i > 0;
        i--
    ) {

        const j =
            Math.floor(
                Math.random() *
                (i + 1)
            );

        [copy[i], copy[j]] =
        [copy[j], copy[i]];

    }

    return copy;

}


/* ==========================================================
   NEXT ROUND
========================================================== */

function honyakuNextRound() {

    honyakuRound++;

    HONYAKU.renderProgress();

    if (honyakuRound > 5) {

        clearInterval(
            honyakuTimerInterval
        );

        alert(`Game Over!

Player 1: ${honyakuScore1}
Player 2: ${honyakuScore2}`);

        honyaku();

        return;
    }

    honyakuCurrentSentence =
        honyakuSentences[
            Math.floor(
                Math.random() *
                honyakuSentences.length
            )
        ];

    renderPlayerBoard(1);
    renderPlayerBoard(2);

    playHonyakuSentence(
        honyakuCurrentSentence
    );

    startHonyakuTimer(
        honyakuNextRound
    );

}


