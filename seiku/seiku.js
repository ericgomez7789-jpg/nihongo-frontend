/* ==========================================================
   SEIKU ENGINE
========================================================== */

let seikuScore1 = 0;
let seikuScore2 = 0;

let seikuRound = 0;

let seikuCurrentIdiom = null;

let seikuTimerInterval = null;

let seikuPlayer1Out = false;
let seikuPlayer2Out = false;
let seikuRoundOver = false;



function showScreen(id) {

    document
        .querySelectorAll(".screen")
        .forEach(screen => {

            screen.classList.add(
                "hidden"
            );

        });

    const screen =
        document.getElementById(
            id
        );

    if (screen) {

        screen.classList.remove(
            "hidden"
        );

    }

}


function wireSeikuReplayButton() {

    const btn =
        document.getElementById(
            "seikuReplayBtn"
        );

    if (!btn) return;

    btn.onclick = () => {

        if (!seikuCurrentIdiom) return;

        const audio = new Audio(
            seikuCurrentIdiom.audio
        );

        audio.play();

    };

}

/* ==========================================================
   SCREEN
========================================================== */

function seiku() {

    window.currentLevel =
        "seiku";

    clearInterval(
        seikuTimerInterval
    );

    seikuScore1 = 0;
    seikuScore2 = 0;

    seikuRound = 0;

    seikuPlayer1Out = false;
    seikuPlayer2Out = false;

    seikuRoundOver = false;

    updateSeikuScorekeepers();

    SeikuProgress.setTotal(
        "seiku",
        seikuData.length
    );

    SEIKU.renderProgress();

    wireSeikuReplayButton();

    showScreen(
        "seikuScreen"
    );

    seikuNextRound();

}

/* ==========================================================
   PROGRESS
========================================================== */

window.SEIKU =
    window.SEIKU || {};

SEIKU.renderProgress =
function () {

    const currentRound =
        Math.min(
            Math.max(
                seikuRound,
                1
            ),
            5
        );

    const totalRounds = 5;

    const percent =
        (currentRound /
         totalRounds) * 100;

    const wrappers =
        document.querySelectorAll(
            "#seikuProgress1, #seikuProgress2"
        );

    wrappers.forEach(
        wrapper => {

            const label =
                wrapper.querySelector(
                    ".seiku-progress-label"
                );

            const bar =
                wrapper.querySelector(
                    ".seiku-progress-bar"
                );

            if (label) {

                label.textContent =
                    `Round: ${currentRound} / ${totalRounds}`;

            }

            if (bar) {

                bar.style.width =
                    `${percent}%`;

            }

        }
    );

};

/* ==========================================================
   IDIOM
========================================================== */

function renderIdiom() {

    document.getElementById(
        "seikuIdiomBox"
    ).textContent =
        seikuCurrentIdiom.idiom;

}

/* ==========================================================
   PLAYER BOARD
========================================================== */

function renderSeikuBoard(
    player
) {

    const container =
        document.getElementById(

            player === 1
                ? "seikuContainer1"
                : "seikuContainer2"

        );

    container.innerHTML = "";

    const choices =
        shuffleArray(
            [...seikuCurrentIdiom.choices]
        );

    choices.forEach(choice => {

        const btn =
            document.createElement(
                "button"
            );

        btn.className =
            "seikuBtn";

        btn.textContent =
            choice;

        btn.addEventListener(
            "click",
            () => {

                checkSeikuAnswer(
                    player,
                    choice,
                    btn
                );

            }
        );

        container.appendChild(
            btn
        );

    });

}

/* ==========================================================
   CHECK ANSWER
========================================================== */

function checkSeikuAnswer(
    player,
    selectedChoice,
    button
) {

    if (seikuRoundOver) return;

    if (

        selectedChoice ===
        seikuCurrentIdiom.meaning

    ) {

        seikuRoundOver = true;

        button.classList.add(
            "correct"
        );

        seikuPlayerWins(
            player
        );

    }

    else {

        button.classList.add(
            "wrong"
        );

        button.disabled = true;

        if (player === 1) {

            seikuPlayer1Out = true;

        }

        else {

            seikuPlayer2Out = true;

        }

        const container =
            document.getElementById(

                player === 1
                    ? "seikuContainer1"
                    : "seikuContainer2"

            );

        container
            .querySelectorAll(
                "button"
            )
            .forEach(btn => {

                btn.disabled = true;

            });

        if (

            seikuPlayer1Out &&
            seikuPlayer2Out

        ) {

            clearInterval(
                seikuTimerInterval
            );

            setTimeout(
                () => {

                    seikuNextRound();

                },
                2000
            );

        }

    }

}

/* ==========================================================
   PLAYER WIN
========================================================== */

function seikuPlayerWins(
    player
) {

    clearInterval(
        seikuTimerInterval
    );

    if (player === 1) {

        seikuScore1++;

    }

    else {

        seikuScore2++;

    }

    updateSeikuScorekeepers();

    SeikuProgress
        .markIdiomComplete(
            "seiku",
            seikuCurrentIdiom.id
        );

    const reveal =
        document.getElementById(
            "seikuReveal"
        );

    reveal.innerHTML = `

        <strong>
            ${seikuCurrentIdiom.idiom}
        </strong>

        <br><br>

        Meaning:

        <br>

        ${seikuCurrentIdiom.meaning}

        <br><br>

        Example:

        <br>

        ${seikuCurrentIdiom.example || ""}

    `;

    reveal.style.display =
        "block";

    setTimeout(
        () => {

            reveal.style.display =
                "none";

            seikuNextRound();

        },
        5000
    );

}


/* ==========================================================
   SCOREKEEPERS
========================================================== */

function updateSeikuScorekeepers() {

    document.getElementById(
        "seikuScore1"
    ).textContent =
        seikuScore1;

    document.getElementById(
        "seikuScore2"
    ).textContent =
        seikuScore2;

}

/* ==========================================================
   TIMER
========================================================== */

function startSeikuTimer(
    onExpire
) {

    let timeLeft = 30;

    const timer =
        document.getElementById(
            "seikuTimer"
        );

    timer.textContent =
        timeLeft;

    clearInterval(
        seikuTimerInterval
    );

    seikuTimerInterval =
        setInterval(
            () => {

                timeLeft--;

                timer.textContent =
                    timeLeft;

                if (
                    timeLeft <= 0
                ) {

                    clearInterval(
                        seikuTimerInterval
                    );

                    onExpire();

                }

            },
            1000
        );

}

/* ==========================================================
   NEXT ROUND
========================================================== */

function seikuNextRound() {

    seikuRound++;

    seikuRoundOver = false;

    SEIKU.renderProgress();

    if (seikuRound > 5) {

        clearInterval(
            seikuTimerInterval
        );

        alert(`Game Over!

Player 1:
${seikuScore1}

Player 2:
${seikuScore2}`);

        seiku();

        return;

    }

    seikuCurrentIdiom =
        seikuData[
            Math.floor(
                Math.random() *
                seikuData.length
            )
        ];

    /* ==========================================
       PLAY AUDIO
    ========================================== */

    const audio = new Audio(
        seikuCurrentIdiom.audio
    );

    audio.play().catch(err => {
        console.log(
            "Audio play failed:",
            err
        );
    });

    seikuPlayer1Out = false;

    seikuPlayer2Out = false;

    renderIdiom();

    renderSeikuBoard(1);

    renderSeikuBoard(2);

    startSeikuTimer(
        seikuNextRound
    );

}


/* ==========================================================
   SHUFFLE
========================================================== */

function shuffleArray(arr) {

    const copy = [...arr];

    for (
        let i =
            copy.length - 1;
        i > 0;
        i--
    ) {

        const j =
            Math.floor(
                Math.random() *
                (i + 1)
            );

        [copy[i], copy[j]] =
        [copy[j], copy[i]];

    }

    return copy;

}


