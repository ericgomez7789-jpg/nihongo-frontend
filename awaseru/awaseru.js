const AwaseruDragModule = {

  setupDropLines(
    player,
    count
  ) {

    const answerArea =
      document.getElementById(
        player === 1
          ? "awaseruAnswerArea1"
          : "awaseruAnswerArea2"
      );

    answerArea.innerHTML = "";

    for (
      let i = 0;
      i < count;
      i++
    ) {

      const slot =
        document.createElement(
          "div"
        );

      slot.className =
        "builtChunk";

      slot.style.minWidth =
        "120px";

      slot.style.minHeight =
        "40px";

      slot.style.border =
        "2px dashed #666";

      slot.style.background =
        "#222";

      slot.style.display =
        "flex";

      slot.style.alignItems =
        "center";

      slot.style.justifyContent =
        "center";

      slot.dataset.index =
        i;

      slot.dataset.player =
        player;

      slot.ondragover =
        e => {
          e.preventDefault();
        };

      slot.ondrop =
        AwaseruDragModule.dropChunk;

      slot.addEventListener(
        "click",
        () => {

          const dragged =
            player === 1
              ? window.awaseruDraggedButton
              : window.awaseruDraggedButton2;

          if (!dragged) {
            return;
          }

          const fakeEvent = {
            preventDefault() {},
            target: slot
          };

          AwaseruDragModule.dropChunk(
            fakeEvent
          );

        }
      );

      answerArea.appendChild(
        slot
      );

    }

  },

  dropChunk(e) {

    e.preventDefault();

    const player =
      Number(
        e.target.dataset.player
      );

    console.log(
      "DROP PLAYER",
      player
    );

    const dragged =
      player === 1
        ? window.awaseruDraggedButton
        : window.awaseruDraggedButton2;

    console.log(
      "DRAGGED BUTTON",
      player,
      dragged?.textContent
    );

    if (!dragged) return;

    const chunkIndex =
      Number(
        dragged.dataset.chunkIndex
      );

    const requiredIndex =
      Number(
        e.target.dataset.index
      );

    console.log(
      "CHECK",
      {
        player,
        chunkIndex,
        requiredIndex,
        text: dragged.textContent
      }
    );

    if (
      chunkIndex !==
      requiredIndex
    ) {

      console.log(
        "WRONG DROP",
        player
      );

      e.target.style.background =
        "#d32f2f";

      setTimeout(() => {

        e.target.style.background =
          "#222";

      }, 300);

      return;

    }

    console.log(
      "CORRECT DROP",
      player
    );

    if (
      e.target.dataset.filled ===
      "true"
    ) {
      return;
    }

    e.target.textContent =
      dragged.textContent;

    e.target.dataset.filled =
      "true";

    e.target.style.background =
      "#4caf50";

    dragged.remove();

    document
      .querySelectorAll(
        ".chunkBtn"
      )
      .forEach(btn => {
        btn.style.outline = "";
      });

    if (player === 1) {

      window.awaseruDraggedButton =
        null;

    } else {

      window.awaseruDraggedButton2 =
        null;

    }

    if (player === 1) {

      correctDropsP1++;

      console.log(
        "P1 DROPS",
        correctDropsP1
      );

      if (
        correctDropsP1 ===
        awaseruCurrentSentence
          .chunks.length
      ) {

        playerWins(1);

      }

    }

    if (player === 2) {

      correctDropsP2++;

      console.log(
        "P2 DROPS",
        correctDropsP2
      );

      if (
        correctDropsP2 ===
        awaseruCurrentSentence
          .chunks.length
      ) {

        playerWins(2);

      }

    }

  }

};




