function playAwaseruChunksInSequence(
  chunkList,
  onComplete
) {

  let index = 0;

  function playNext() {

    if (
      index >= chunkList.length
    ) {

      if (
        typeof onComplete ===
        "function"
      ) {
        onComplete();
      }

      return;
    }

    const audio =
      new Audio(
        chunkList[index]
      );

    audio.onended = () => {

      index++;

      playNext();

    };

    audio.onerror = () => {

      index++;

      playNext();

    };

    audio.play().catch(() => {

      index++;

      playNext();

    });

  }

  playNext();

}


