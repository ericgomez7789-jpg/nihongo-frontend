/* ==========================================================
   SHUFFLE
========================================================== */

function shuffleArray(arr) {

  const copy = [...arr];

  for (
    let i = copy.length - 1;
    i > 0;
    i--
  ) {

    const j =
      Math.floor(
        Math.random() *
        (i + 1)
      );

    [copy[i], copy[j]]
      =
    [copy[j], copy[i]];

  }

  return copy;

}

/* ==========================================================
   SCRAMBLE
========================================================== */

function getScrambledChunks(
  sentence,
  player
) {

  const original =
    [...sentence.chunks];

  let scrambled =
    shuffleArray(original);

  let key =
    scrambled
      .map(
        chunk =>
        sentence.chunks.indexOf(chunk)
      )
      .join("-");

  if (
    player === 1 &&
    key === lastScrambleP1
  ) {

    scrambled =
      shuffleArray(original);

    key =
      scrambled
        .map(
          chunk =>
          sentence.chunks.indexOf(chunk)
        )
        .join("-");
  }

  if (
    player === 2 &&
    key === lastScrambleP2
  ) {

    scrambled =
      shuffleArray(original);

    key =
      scrambled
        .map(
          chunk =>
          sentence.chunks.indexOf(chunk)
        )
        .join("-");
  }

  if (player === 1) {
    lastScrambleP1 = key;
  }

  if (player === 2) {
    lastScrambleP2 = key;
  }

  return scrambled;

}

